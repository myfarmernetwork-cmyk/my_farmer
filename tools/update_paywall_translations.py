# Map locale file stems to base language patch
FILE_TO_LANG = {
    "hr": "hr",
    "hr-HR": "hr",
    "hr-BA": "hr",
    "bs": "bs",
    "sr": "sr",
    "sr-BA": "sr",
    "sr-RS": "sr",
    "en": "en",
    "de": "de",
    "it": "it",
    "fr": "fr",
    "es": "es",
    "pl": "pl",
    "cs": "cs",
    "sv": "sv",
    "tr": "tr",
    "ru": "ru",
    "uk": "uk",
    "zh": "zh",
    "hi": "hi",
    "id": "id",
    "sw": "sw",
    "ar": "ar",
}


def main() -> None:
    updated = 0
    for path in sorted(TRANS_DIR.glob("*.json")):
        stem = path.stem
        lang = FILE_TO_LANG.get(stem)
        if lang is None:
            print(f"skip unknown locale: {stem}")
            continue
        patch = PATCHES[lang]
        data = json.loads(path.read_text(encoding="utf-8"))
        data.update(patch)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        updated += 1
        print(f"updated {path.name}")
    print(f"done: {updated} files")


if __name__ == "__main__":
    main()
