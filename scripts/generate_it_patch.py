    extra = [k for k in TRANSLATIONS if k not in needs]
    if extra:
        raise SystemExit(f"Extra translations not in needs: {extra[:10]}...")

    patch = {k: TRANSLATIONS[k] for k in needs}
    OUT.parent.mkdir(parents=True, exist_ok=True)
