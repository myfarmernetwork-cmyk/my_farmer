# South Slavic locales inherit Croatian strings
for code in ("hr-HR", "hr-BA", "bs", "sr", "sr-RS", "sr-BA"):
    LOCALE_STRINGS[code] = dict(LOCALE_STRINGS["hr"])


def resolve_locale(code: str) -> dict[str, str]:
    if code in LOCALE_STRINGS and LOCALE_STRINGS[code]:
        return LOCALE_STRINGS[code]
    return LOCALE_STRINGS["en"]


def main() -> None:
    updated = 0
    for path in sorted(OUT_DIR.glob("*.json")):
        code = path.stem
        strings = resolve_locale(code)
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        changed = False
        for key in KEYS:
            if key in strings:
                if data.get(key) != strings[key]:
                    data[key] = strings[key]
                    changed = True
        if changed:
            path.write_text(
                json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            updated += 1
            print(f"updated {path.name}")
    print(f"Done. Updated {updated} files.")


if __name__ == "__main__":
    main()
